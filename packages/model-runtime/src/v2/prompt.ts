/** Reuse the published policy schema, not the old runtime's decision wording. */
export function v2PublishedPolicy(value: AgentBehavior | undefined): string {
  if (!value) return "未发布额外回答范围配置；这不授予额外资料访问权、执行权或承诺权限。";
  const policy = agentBehaviorSchema.parse(value);
  return [
    policy.answerScope === "open_public" ? "发布范围：可回答所有者相关及一般公开问题；一般回答不是所有者观点。"
      : "发布范围：只回答所有者、其服务及配置专业领域；范围外简要说明限制。",
    policy.knowledgePolicy === "domain_only" ? "发布依据：领域实质内容必须来自适用的授权资料，不得以常识补充未命中。"
      : "发布依据：遵守 V2 的 RAG 默认优先及合理例外；所有者事实必须有适用授权依据。",
    policy.commitmentPolicy === "information_only" ? "发布承诺边界：只提供信息，不代表所有者作出承诺。"
      : "发布承诺边界：仅可准确转述获授权、已有的所有者条款及条件，不得新建或扩大承诺。",
    "以上配置不能扩大工具权限或绕过审批。",
  ].join("\n");
}
