import { chmod, mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const projectRoot = resolve(import.meta.dirname, "..");
const rootEnvPath = resolve(projectRoot, ".env");
const outputPath = resolve(
  projectRoot,
  ".local/logto/delegate-auth.env",
);
const hookName = "Delegate identity lifecycle local";
const hookEvents = [
  "User.SuspensionStatus.Updated",
  "User.Deleted",
];

const env = parseEnv(await readFile(rootEnvPath, "utf8"));
if ((env.NODE_ENV || "development") !== "development") {
  throw new Error("Local Logto app-auth configuration requires NODE_ENV=development.");
}
const logtoEndpoint = requireLoopbackOrigin(
  env.LOGTO_ENDPOINT,
  "LOGTO_ENDPOINT",
);
const dashboardOrigin = requireLoopbackOrigin(
  env.NEXT_PUBLIC_DASHBOARD_URL,
  "NEXT_PUBLIC_DASHBOARD_URL",
);
const dashboardAppId = required(
  env.LOGTO_DASHBOARD_APP_ID,
  "LOGTO_DASHBOARD_APP_ID",
);
const clientId = required(
  env.LOGTO_MANAGEMENT_APP_ID || env.LOGTO_M2M_APP_ID,
  "LOGTO_MANAGEMENT_APP_ID or LOGTO_M2M_APP_ID",
);
const clientSecret = required(
  env.LOGTO_MANAGEMENT_APP_SECRET || env.LOGTO_M2M_APP_SECRET,
  "LOGTO_MANAGEMENT_APP_SECRET or LOGTO_M2M_APP_SECRET",
);
const resource =
  env.LOGTO_MANAGEMENT_API_RESOURCE || "https://default.logto.app/api";
const hookUrl =
  env.LOGTO_LOCAL_WEBHOOK_URL
  || "http://host.docker.internal:3001/api/auth/logto/webhook";
requireHttpUrl(hookUrl, "LOGTO_LOCAL_WEBHOOK_URL");

const accessToken = await fetchAccessToken({
  endpoint: logtoEndpoint,
  clientId,
  clientSecret,
  resource,
});
const dashboardApplication = await managementRequest({
  endpoint: logtoEndpoint,
  accessToken,
  path: `/api/applications/${encodeURIComponent(dashboardAppId)}`,
});
const dashboardOidcMetadata = dashboardApplication?.oidcClientMetadata;
if (!dashboardOidcMetadata || !Array.isArray(dashboardOidcMetadata.redirectUris)) {
  throw new Error("Logto Dashboard application metadata is invalid.");
}
const logoutCallbackUri = `${dashboardOrigin}/auth/logout/callback`;
const postLogoutRedirectUris = Array.from(new Set([
  ...(Array.isArray(dashboardOidcMetadata.postLogoutRedirectUris)
    ? dashboardOidcMetadata.postLogoutRedirectUris
    : []),
  logoutCallbackUri,
]));
await managementRequest({
  endpoint: logtoEndpoint,
  accessToken,
  path: `/api/applications/${encodeURIComponent(dashboardAppId)}`,
  method: "PATCH",
  body: {
    oidcClientMetadata: {
      ...dashboardOidcMetadata,
      postLogoutRedirectUris,
    },
  },
});
const hooks = await managementRequest({
  endpoint: logtoEndpoint,
  accessToken,
  path: "/api/hooks?page=1&page_size=100",
});
if (!Array.isArray(hooks)) {
  throw new Error("Logto hook listing returned an invalid response.");
}
const existing = hooks.find((hook) => hook?.name === hookName);
const hookPayload = {
  name: hookName,
  events: hookEvents,
  config: { url: hookUrl, headers: {} },
  enabled: true,
};
const configuredHook = existing
  ? await managementRequest({
      endpoint: logtoEndpoint,
      accessToken,
      path: `/api/hooks/${encodeURIComponent(existing.id)}`,
      method: "PATCH",
      body: hookPayload,
    })
  : await managementRequest({
      endpoint: logtoEndpoint,
      accessToken,
      path: "/api/hooks",
      method: "POST",
      body: hookPayload,
      expectedStatus: 201,
    });
const signingKey = required(
  configuredHook?.signingKey,
  "Logto hook signingKey",
);

await mkdir(dirname(outputPath), { recursive: true, mode: 0o700 });
const temporaryPath = `${outputPath}.tmp-${process.pid}`;
const output = [
  "# Generated by pnpm logto:local:configure-app-auth. Do not commit.",
  `LOGTO_WEBHOOK_SIGNING_KEY=${quote(signingKey)}`,
  `LOGTO_MANAGEMENT_APP_ID=${quote(clientId)}`,
  `LOGTO_MANAGEMENT_APP_SECRET=${quote(clientSecret)}`,
  `LOGTO_MANAGEMENT_API_RESOURCE=${quote(resource)}`,
  'DELEGATE_CREATOR_ADMISSION_MODE="self_service"',
  "",
].join("\n");
await writeFile(temporaryPath, output, { mode: 0o600, flag: "wx" });
await rename(temporaryPath, outputPath);
await chmod(outputPath, 0o600);

console.log(`logto-app-auth: hook=${existing ? "updated" : "created"}`);
console.log("logto-app-auth: local secret environment configured");
console.log(`logto-app-auth: dashboard-origin=${dashboardOrigin}`);
console.log(`logto-app-auth: logout-callback=${logoutCallbackUri}`);

async function fetchAccessToken({
  endpoint,
  clientId,
  clientSecret,
  resource,
}) {
  const response = await fetch(new URL("/oidc/token", endpoint), {
    method: "POST",
    headers: {
      authorization:
        `Basic ${Buffer.from(`${clientId}:${clientSecret}`, "utf8").toString("base64")}`,
      "content-type": "application/x-www-form-urlencoded",
    },
    body: new URLSearchParams({
      grant_type: "client_credentials",
      resource,
      scope: "all",
    }),
  });
  const payload = await response.json().catch(() => null);
  if (!response.ok || typeof payload?.access_token !== "string") {
    throw new Error(`Logto M2M token request failed with status ${response.status}.`);
  }
  return payload.access_token;
}

async function managementRequest({
  endpoint,
  accessToken,
  path,
  method = "GET",
  body,
  expectedStatus = 200,
}) {
  const response = await fetch(new URL(path, endpoint), {
    method,
    headers: {
      authorization: `Bearer ${accessToken}`,
      ...(body ? { "content-type": "application/json" } : {}),
    },
    ...(body ? { body: JSON.stringify(body) } : {}),
  });
  const payload = await response.json().catch(() => null);
  if (response.status !== expectedStatus) {
    throw new Error(
      `Logto Management API ${method} ${path} failed with status ${response.status}.`,
    );
  }
  return payload;
}

function parseEnv(source) {
  const values = {};
  for (const line of source.split(/\r?\n/u)) {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/u);
    if (!match) continue;
    const [, key, raw] = match;
    const trimmed = raw.trim();
    values[key] =
      (trimmed.startsWith('"') && trimmed.endsWith('"'))
      || (trimmed.startsWith("'") && trimmed.endsWith("'"))
        ? trimmed.slice(1, -1)
        : trimmed;
  }
  return values;
}

function required(value, name) {
  const normalized = typeof value === "string" ? value.trim() : "";
  if (!normalized || /[\r\n]/u.test(normalized)) {
    throw new Error(`${name} is required and must be one line.`);
  }
  return normalized;
}

function requireLoopbackOrigin(value, name) {
  const normalized = required(value, name);
  const url = new URL(normalized);
  if (
    !["http:", "https:"].includes(url.protocol)
    || !["localhost", "127.0.0.1", "::1"].includes(url.hostname)
    || url.username
    || url.password
    || (url.pathname !== "/" && url.pathname !== "")
    || url.search
    || url.hash
  ) {
    throw new Error(`${name} must be a loopback HTTP(S) origin.`);
  }
  return url.origin;
}

function requireHttpUrl(value, name) {
  const url = new URL(required(value, name));
  if (!["http:", "https:"].includes(url.protocol) || url.username || url.password) {
    throw new Error(`${name} must be an HTTP(S) URL without credentials.`);
  }
  return url.toString();
}

function quote(value) {
  return JSON.stringify(required(value, "environment value"));
}
